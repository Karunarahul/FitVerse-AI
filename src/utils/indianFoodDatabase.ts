/**
 * Calculates scaled nutrients based on consumed gram quantity.
 * Example: 150g of 130 kcal/100g => 195 kcal
 */
export function calculateScaledNutrients(item: FoodDatabaseItem, quantityGrams: number) {
  const ratio = Math.max(0, quantityGrams) / 100;
  return {
    calories: Math.round(item.per100g.calories * ratio),
    protein: parseFloat((item.per100g.protein * ratio).toFixed(1)),
    carbs: parseFloat((item.per100g.carbs * ratio).toFixed(1)),
    fat: parseFloat((item.per100g.fat * ratio).toFixed(1)),
    fiber: parseFloat((item.per100g.fiber * ratio).toFixed(1)),
    saturatedFat: item.per100g.saturatedFat ? parseFloat((item.per100g.saturatedFat * ratio).toFixed(1)) : undefined,
    sodiumMg: Math.round(item.per100g.sodiumMg * ratio),
    calciumMg: Math.round(item.per100g.calciumMg * ratio),
    ironMg: parseFloat((item.per100g.ironMg * ratio).toFixed(1)),
    potassiumMg: Math.round(item.per100g.potassiumMg * ratio),
  };
}
